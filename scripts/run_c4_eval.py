"""Run the preliminary C4 evaluation and write reproducible result files.

    python3 scripts/run_c4_eval.py                 # stress test + cached natural set
    python3 scripts/run_c4_eval.py --refresh       # (re)generate natural set with Ollama
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from c4 import OllamaExplanationGenerator
from c4.adapters import load_json
from c4.evaluation import evaluate_bloom, evaluate_natural, evaluate_sensitivity, evaluate_stress

DATA = ROOT / "c4" / "data"
RESULTS = ROOT / "c4" / "results"


def fmt(value) -> str:
    return "n/a" if value is None else f"{value}"


def render_bloom(bloom: dict) -> list[str]:
    lines = [
        "",
        "## C. Bloom-level estimator against labelled items",
        f"- Item set `{bloom['version']}`: {bloom['items']} items, 6 levels. {bloom['provenance']}",
        f"- Split rule: {bloom['split_rule']}",
        "",
        "| Split | Estimator | Items | Accuracy % | 95% CI | Within one level % | Mean abs. error | Macro-F1 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for split, row in bloom["splits"].items():
        for name in ("v1", "v2"):
            r = row[name]
            lines.append(f"| {split} | {name} | {r['items']} | {r['accuracy']} | {r['accuracy_ci95']} | "
                         f"{r['within_one']} | {r['mean_abs_error']} | {r['macro_f1']} |")
    lines += ["", f"**Caveat.** {bloom['caveat']}"]
    return lines


def render(stress: dict, natural: dict | None, sensitivity: list[dict], bloom: dict | None = None) -> str:
    det = stress["detection"]
    base = stress["baseline_unverified_reference"]
    lines = [
        "# C4 preliminary evaluation (PP1)",
        "",
        "Generated by `python3 scripts/run_c4_eval.py`. Pilot parameters, not validated research values.",
        "",
        "## A. Controlled violation stress test",
        f"- Corpus `{stress['corpus_version']}`: {stress['cases']} cases "
        f"({stress['targets']} concepts x {len(stress['profiles'])} learner profiles), {stress['claims']} atomic claims.",
        f"- Reference factual labels: {stress['reference_factual_labels']}",
        f"- Reference cognitive labels: {stress['reference_cognitive_labels']}",
        f"- Label provenance: {stress['label_provenance']}.",
        "",
        "### Verifier detection vs reference labels (initial claims)",
        "| Dimension | TP | FP | FN | Precision | Recall | F1 |",
        "|---|---|---|---|---|---|---|",
    ]
    for key in ("factual", "cognitive_all", "bloom_mismatch", "unmastered_prerequisite"):
        row = det[key]
        lines.append(f"| {key} | {row['tp']} | {row['fp']} | {row['fn']} | "
                     f"{fmt(row['precision'])} | {fmt(row['recall'])} | {fmt(row['f1'])} |")
    lines += [
        "",
        f"Exact-label accuracy: factual {det['exact_factual_label_accuracy']}%, "
        f"cognitive {det['exact_cognitive_label_accuracy']}%.",
        "",
        "### Unverified baseline vs repaired conditions",
        "Baseline = original explanations, rates from the reference labels. Repaired rates are re-measured by the "
        "full verifier on each condition's final text (same verifier, so not independent).",
        "",
        "| Condition | Hallucination rate % | Cognitive-mismatch rate % | Cases with violation | 95% CI | McNemar fixed/worsened, p |",
        "|---|---|---|---|---|---|",
        f"| Unverified baseline | {base['hallucination_rate']} | {base['cognitive_mismatch_rate']} | "
        f"{base['cases_with_violation']}/{stress['cases']} | {stress['baseline_cases_with_violation_ci95']} | - |",
    ]
    for name, row in stress["conditions_after_repair"].items():
        m = row["mcnemar_vs_baseline"]
        lines.append(f"| {name} | {row['hallucination_rate']} | {row['cognitive_mismatch_rate']} | "
                     f"{row['cases_with_violation']}/{stress['cases']} | {row['cases_with_violation_ci95']} | "
                     f"{m['fixed']}/{m['worsened']}, p={m['p_exact']} |")
    rw = stress["rewrite"]
    lines += [
        "",
        f"Rewrite (full C4): {rw['corrected']}/{rw['claims_sent']} violating claims corrected "
        f"(success {fmt(rw['success_rate'])}%); new violations introduced: {rw['new_violations_introduced']}.",
        f"Mean full-C4 latency per case: {stress['conditions_after_repair']['full_c4']['mean_latency_ms']} ms "
        "(verifier only; 0 LLM calls).",
        "",
        f"**Caveat.** {stress['caveat']}",
    ]
    if natural:
        lines += [
            "",
            "## B. Natural generation (exploratory)",
            f"- Generator: `{natural['model']}`; {natural['explanations']} explanations, {natural['claims']} claims.",
            f"- Before C4: hallucination {natural['before']['hallucination_rate']}%, "
            f"cognitive mismatch {natural['before']['cognitive_mismatch_rate']}%, "
            f"inconclusive claims {natural['before']['inconclusive']}.",
            f"- After C4: hallucination {natural['after']['hallucination_rate']}%, "
            f"cognitive mismatch {natural['after']['cognitive_mismatch_rate']}%, "
            f"inconclusive claims {natural['after']['inconclusive']}.",
            f"- Explanations with at least one flagged claim: {natural['explanations_with_flagged_claim']}/"
            f"{natural['explanations']} (95% CI {natural['explanations_with_flagged_claim_ci95']}); "
            f"rewrite success {fmt(natural['rewrite_success_rate'])}%; "
            f"explanations with unresolved claims: {natural['unresolved_explanations']}.",
            f"- **Caveat.** {natural['caveat']}",
            "",
            "### Entailment-threshold sensitivity (pilot tuning)",
            "| entail_similarity | stress precision | stress recall | stress F1 | natural % claims not graph-supported |",
            "|---|---|---|---|---|",
        ]
        for row in sensitivity:
            lines.append(f"| {row['entail_similarity']} | {fmt(row['stress_factual_precision'])} | "
                         f"{fmt(row['stress_factual_recall'])} | {fmt(row['stress_factual_f1'])} | "
                         f"{row['natural_not_graph_supported_pct']} |")
        lines += [
            "",
            "Reading: the strict rule (default 0.6) cannot distinguish a faithful paraphrase or benign "
            "elaboration from an invention, so the natural-generation 'hallucination' figure is really "
            "'not supported by the two graph facts'. Lowering the threshold trades that off against "
            "missed violations on the stress set. Resolving this needs sentence-to-atomic-claim "
            "decomposition and an NLI model (planned), judged against human labels.",
            "",
            "### Examples",
        ]
        for item in natural["examples"]:
            lines += [f"- `{item['case_id']}`", f"  - original: {item['original']}", f"  - final: {item['final']}"]
    if bloom:
        lines += render_bloom(bloom)
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--refresh", action="store_true", help="Generate missing natural explanations with Ollama")
    parser.add_argument("--model", default="qwen3:4b")
    args = parser.parse_args()

    kg = load_json(DATA / "knowledge_graph.json")
    RESULTS.mkdir(exist_ok=True)
    stress = evaluate_stress(kg)
    generator = OllamaExplanationGenerator(model=args.model) if args.refresh else None
    natural = evaluate_natural(kg, DATA / "natural_cache.json", generator)
    natural = natural if natural["explanations"] else None
    (RESULTS / "stress_test.json").write_text(json.dumps(stress, indent=2) + "\n", encoding="utf-8")
    if natural:
        (RESULTS / "natural.json").write_text(json.dumps(natural, indent=2) + "\n", encoding="utf-8")
    sensitivity = evaluate_sensitivity(kg, DATA / "natural_cache.json")
    (RESULTS / "sensitivity.json").write_text(json.dumps(sensitivity, indent=2) + "\n", encoding="utf-8")
    bloom = evaluate_bloom(DATA / "bloom_items.json")
    (RESULTS / "bloom_classifier.json").write_text(json.dumps(bloom, indent=2) + "\n", encoding="utf-8")
    report = render(stress, natural, sensitivity, bloom)
    (RESULTS / "RESULTS.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
