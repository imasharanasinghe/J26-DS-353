"""Phase 3 and E3: planted-error test for the Graph Auditor, and the downstream effect on the verifier.

    python3 scripts/run_c4_audit.py                       # sizes 60,120,300,600 x 5 seeds (about a minute)
    python3 scripts/run_c4_audit.py --seeds 10 --fraction 0.2

Writes c4/results/audit.json and c4/results/AUDIT.md. Seeded, no model, no network. The cohort is
simulated, so numbers measure the method under the generator's assumptions, not real classes.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from c4 import audit_loop, audit_sim
from c4.adapters import load_json

DATA = ROOT / "c4" / "data"
RESULTS = ROOT / "c4" / "results"


def f(cell: dict) -> str:
    return "n/a" if cell["mean"] is None else f"{cell['mean']:.2f} ± {cell['sd']:.2f}"


def render(sweep: dict, loop: dict) -> str:
    lines = ["# C4 Graph Auditor: planted-error results", "",
             "Generated by `python3 scripts/run_c4_audit.py`. Simulated cohorts on the 30-concept C3 graph "
             f"({sweep['true_edges']} true edges). {int(sweep['fraction_corrupted_per_type'] * 100)}% of edges are "
             "deleted, a further 15% reversed and as many spurious ones added before the audit. Mean ± sd over seeds.", "",
             "## Detecting wrong edges (reversed and spurious) in the graph being audited", "",
             "Strict = status Reversed or Unsupported. Contested edges are not counted as flags. "
             "Baselines: *co-occurrence* flags edges with an unadjusted odds ratio below 4; "
             "*order only* flags edges whose prerequisite is usually learned after the concept.", "",
             "| Students | Ours precision | Ours recall | Ours F1 | Ours F1 incl. Contested | Co-occurrence F1 | Order-only F1 | Clean edges flagged | Clean edges Contested |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in sweep["rows"]:
        lines.append(f"| {r['students']} | {f(r['ours_strict_precision'])} | {f(r['ours_strict_recall'])} | {f(r['ours_strict_f1'])} | "
                     f"{f(r['ours_incl_contested_f1'])} | {f(r['baseline_cooccurrence_f1'])} | {f(r['baseline_order_f1'])} | "
                     f"{f(r['clean_edges_flagged'])} | {f(r['clean_edges_contested_share'])} |")
    lines += ["", "## Recovering deleted edges (Missing candidates)", "",
              "Baseline: the top-k unlinked pairs by raw odds ratio, k = number deleted (the baseline is told k; the auditor is not).", "",
              "| Students | Recall | Precision | Baseline recall |", "|---|---|---|---|"]
    for r in sweep["rows"]:
        lines.append(f"| {r['students']} | {f(r['missing_recall'])} | {f(r['missing_precision'])} | {f(r['missing_baseline_recall'])} |")
    lines += ["", "## Downstream: does the audit reduce wrong \"review first\" detours? (E3)", "",
              "Per (student, target) pair. *audit* drops Unsupported and Reversed edges, as the verifier now does. "
              "*audit + approved* also applies the correct proposals; the lecturer is an oracle, so it is an upper bound.", "",
              "| Students | Condition | Wrong detours | Missed prerequisites | Share of true prerequisites missed |",
              "|---|---|---|---|---|"]
    for r in loop["rows"]:
        for name in ("no_audit", "audit", "audit_approved"):
            c = r[name]
            lines.append(f"| {r['students']} | {name} | {c['wrong_detours_per_pair']:.3f} | "
                         f"{c['missed_prereqs_per_pair']:.3f} | {c['missed_share_of_true']:.3f} |")
    lines += ["", "## Reading these results honestly", "",
              "- **The order-only baseline is strong here because the generator makes learning order follow prerequisite depth.** "
              "That is exactly the curriculum-order confound NEW.md warns about, so a strong order baseline in simulation "
              "says nothing about whether order evidence survives a real timetable. The implication and ability-adjusted lift tests "
              "do not depend on order.",
              "- The raw co-occurrence baseline cannot flag spurious edges: strong students master everything, so any two concepts correlate.",
              "- Precision is high and recall plateaus below 1: spurious edges between concepts that share prerequisites keep some "
              "association and end up Contested rather than Unsupported. That is the intended behaviour (evidence, not proof).",
              "- Small cohorts give wide intervals, so most edges are Contested below about 120 students.",
              "- Real-data validation (ASSISTments, then SLIIT data) is not done: `audit_sim.observations_from_rows` is the loader.", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", type=int, default=5)
    parser.add_argument("--fraction", type=float, default=0.15)
    args = parser.parse_args()
    kg = load_json(DATA / "c3_import" / "graph_30_concepts.json")
    sweep = audit_sim.sweep(kg, (60, 120, 300, 600), args.seeds, args.fraction)
    loop = audit_loop.study(kg, (120, 300, 600), args.seeds, args.fraction)
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "audit.json").write_text(json.dumps({"planted_error": sweep, "downstream": loop}, indent=2), encoding="utf-8")
    (RESULTS / "AUDIT.md").write_text(render(sweep, loop), encoding="utf-8")
    print("wrote c4/results/audit.json and AUDIT.md")


if __name__ == "__main__":
    main()
