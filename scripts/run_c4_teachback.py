"""Phase 1 and 2: validate the knowledge-restricted novice, then score a demo exam.

    python3 scripts/run_c4_teachback.py                    # lexical control only (no model, seconds)
    python3 scripts/run_c4_teachback.py --llm              # also the local Ollama novice (slow: ~15 min)
    python3 scripts/run_c4_teachback.py --llm --llm-seeds 2 --llm-runs 4 --model qwen3:4b

Writes c4/results/teachback.json and c4/results/TEACHBACK.md.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from c4 import instrument, synthetic, teachback
from c4.adapters import load_json
from c4.novice import LexicalNovice, OllamaNovice
from c4.testbank import build_test

DATA = ROOT / "c4" / "data"
RESULTS = ROOT / "c4" / "results"


def gate_rows(gate: dict) -> list[str]:
    d, leak, rel, fair = gate["discrimination"], gate["leakage"], gate["reliability"], gate["fairness"]
    out = [f"### Novice: `{gate['novice']}` ({gate['items']} items)", "",
           f"- **Gate passed: {gate['gate_passed']}** (no leakage and every ordering/invariance check passes)",
           f"- Leakage: empty text scores {leak['empty_text']['score']:.3f}, unrelated text on held-out concepts "
           f"{leak['unrelated_text_heldout_items']['score']:.3f}; chance if forced to guess "
           f"{leak['chance_if_forced_to_guess']:.2f}; leaks: **{leak['leaks']}**",
           f"- Reliability ({rel['runs']} runs, variant `{rel['variant']}`, temperature {rel['temperature']}): "
           f"mean {rel['mean_score']}, sd {rel['sd']}, range {rel['range']}, per-item agreement {rel['item_agreement']}", "",
           "| Variant | Score | Net (right minus wrong/(k-1)) |", "|---|---|---|"]
    for name, row in d["means"].items():
        out.append(f"| {name} | {row['score']:.3f} | {row['net']:.3f} |")
    out += ["", "| Expected | Mean difference | 95% CI | Pass |", "|---|---|---|---|"]
    for c in d["ordering_checks"]:
        out.append(f"| {c['expect']} | {c['mean_difference']} | {c['ci95']} | {c['passes']} |")
    for c in d["invariance_checks"]:
        out.append(f"| {c['expect']} | {c['mean_difference']} | | {c['passes']} |")
    out += ["", f"Fairness (same content, weaker English): clean prose {fair['clean_prose_score']}; "
            + "; ".join(f"{k} gap {v['mean_gap']} (CI {v['ci95']})" for k, v in fair["gap_vs_clean_prose"].items())
            + f"; concept-list score {fair['concept_list_score']} (gap {fair['concept_list_gap']}).", ""]
    return out


def render(result: dict) -> str:
    lines = ["# C4 teach-back instrument: validation results", "",
             "Generated by `python3 scripts/run_c4_teachback.py`. Synthetic explanations built from the graph "
             "(known gaps), so no humans are involved and no number here says anything about real students.", "",
             "Reading guide: a score is the share of hidden-test items the novice answered correctly from the text "
             "alone (\"I don't know\" counts as wrong). The lexical novice is a deterministic control with zero "
             "leakage by construction; the LLM novice is the candidate instrument.", ""]
    for gate in result["gates"]:
        lines += gate_rows(gate)
    demo = result["demo_exam"]
    lines += ["## Demo exam (lexical novice, heap lecture)", "",
              "| Student | Overall | Coverage | Contradicted statements | Flags |", "|---|---|---|---|---|"]
    for name, row in demo.items():
        lines.append(f"| {name} | {row['novice_test']['overall']['score']:.2f} | {row['coverage']['coverage']} | "
                     f"{len(row['claim_check']['contradicted'])} | {'; '.join(row['flags']) or '-'} |")
    lines += ["", "## Limits", "",
              "- Items are a pilot bank (24 items, 7 concepts); difficulty is not calibrated, so ceiling effects are possible.",
              "- The lexical novice cannot see word order or paraphrase; an LLM novice can, but may leak knowledge.",
              "- None of this is validity evidence. Validity needs the human pilot (SLIIT ethics approval).", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--llm", action="store_true")
    parser.add_argument("--model", default="qwen3:4b")
    parser.add_argument("--seeds", type=int, default=10)
    parser.add_argument("--llm-seeds", type=int, default=2)
    parser.add_argument("--llm-runs", type=int, default=4)
    args = parser.parse_args()

    kg = load_json(DATA / "knowledge_graph.json")
    items = build_test(kg)
    gates = [instrument.run_gate(LexicalNovice(kg), kg, items, seeds=args.seeds, runs=3)]
    if args.llm:
        started = time.time()
        novice = OllamaNovice(model=args.model)
        print("running LLM novice gate (slow)...", flush=True)
        gates.append(instrument.run_gate(novice, kg, items, seeds=args.llm_seeds, runs=args.llm_runs))
        print(f"done in {time.time() - started:.0f}s", flush=True)

    heaps = ["heap", "binary_tree", "arrays"]
    lexical = LexicalNovice(kg)
    demo = {name: teachback.score_exam(kg, lexical, name, synthetic.explain(kg, variant, 0, heaps), heaps)
            for name, variant in (("complete", "complete"), ("one_step_missing", "missing_one"),
                                  ("half", "half"), ("misconception", "wrong"), ("empty", "empty"))}
    result = {"items": len(items), "gates": gates, "demo_exam": demo}
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "teachback.json").write_text(json.dumps(result, indent=2, default=str), encoding="utf-8")
    (RESULTS / "TEACHBACK.md").write_text(render(result), encoding="utf-8")
    print("wrote c4/results/teachback.json and TEACHBACK.md")


if __name__ == "__main__":
    main()
