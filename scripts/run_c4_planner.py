"""Phase 4: block-plan simulation (uniform vs tiered vs evidence-driven) at the same practice budget.

    python3 scripts/run_c4_planner.py
    python3 scripts/run_c4_planner.py --budget 6 --students 300 --seeds 12

Writes c4/results/planner.json and c4/results/PLANNER.md. Seeded; no model or network. Uses seeds from
100 up because the plan was tuned on seeds 0-5.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from c4 import planner
from c4.adapters import load_json

RESULTS = ROOT / "c4" / "results"
LABELS = {
    "share_students_with_any_concept_below_floor": "Students with any concept below the floor",
    "mean_share_of_concepts_below_floor": "Concepts below the floor (per student)",
    "exam_mean": "Exam mean",
    "exam_sd": "Exam spread (sd)",
}


def render(runs: list[dict]) -> str:
    lines = ["# C4 block-plan simulation", "",
             "Generated by `python3 scripts/run_c4_planner.py`. Simulated learners (learning rate, diminishing returns, "
             "prerequisite gating, forgetting, noisy quizzes); same practice budget for every plan; seeds 100 and up. "
             "**This reflects the simulator's assumptions, not real students.**", ""]
    for result in runs:
        lines += [f"## Budget {result['budget_per_week']} h/week, {result['students']} students x {result['seeds']} seeds, "
                  f"floor {result['floor']}, {result['weeks']} weeks", "",
                  "| Metric | Uniform | Tiered | Evidence |", "|---|---|---|---|"]
        for key, label in LABELS.items():
            s = result["summary"]
            lines.append(f"| {label} | {s['uniform'][key]} | {s['tiered'][key]} | {s['evidence'][key]} |")
        lines += ["", "Paired differences (evidence minus other, mean and 95% bootstrap CI over seeds):", ""]
        for key, value in result["paired_differences"].items():
            lines.append(f"- {key}: {value['mean']} {value['ci95']}")
        lines.append("")
    lines += ["## Reading this honestly", "",
              "- Spreading practice by gap lowers the number of *concepts* below the floor per student, but with noisy "
              "weekly checks it leaves more students with *at least one* concept just under the floor than a uniform plan. "
              "The 'nobody under the floor' goal is therefore not met by this plan in this simulation.",
              "- The plan was tuned (guess-corrected estimates, a baseline share, smoothing) on seeds 0-5; these results use fresh seeds.",
              "- The tiered plan, which uses last semester's marks, is no better than uniform here: marks only weakly predict learning rate in this model.",
              "- Nothing here shows the plan helps real students. The pilot is needed.", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--budget", type=float, nargs="*", default=[6.0, 8.0, 12.0])
    parser.add_argument("--students", type=int, default=200)
    parser.add_argument("--seeds", type=int, default=8)
    args = parser.parse_args()
    kg = load_json(ROOT / "c4" / "data" / "c3_import" / "graph_30_concepts.json")
    runs = [planner.compare(kg, seeds=args.seeds, students=args.students, seed_offset=100, budget=b) for b in args.budget]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "planner.json").write_text(json.dumps(runs, indent=2), encoding="utf-8")
    (RESULTS / "PLANNER.md").write_text(render(runs), encoding="utf-8")
    print("wrote c4/results/planner.json and PLANNER.md")


if __name__ == "__main__":
    main()
