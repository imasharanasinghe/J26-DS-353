"""Run the Bloom-progression experiments and write reproducible result files.

    python3 scripts/run_c4_progression.py                 # 300 simulated learners, 8 sessions
    python3 scripts/run_c4_progression.py --learners 600 --sessions 10 --seed 1

Writes c4/results/progression.json and c4/results/PROGRESSION.md. Everything is seeded and
needs no model or network.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from c4.adapters import load_json
from c4.evaluation import evaluate_progressive_stress
from c4.simulation import ABLATIONS, CONDITIONS, run_experiment

DATA = ROOT / "c4" / "data"
RESULTS = ROOT / "c4" / "results"
MODEL_TEXT = {
    "zpd": "ZPD learner (the design hypothesis: stretching within reach teaches best)",
    "flat": "Flat control (explanation level does not affect learning)",
    "matched": "Matched control (learning is best at the learner's own level; stretching hurts)",
}


def fmt_p(wilcoxon: dict) -> str:
    p = wilcoxon.get("p")
    return "n/a" if p is None else ("<0.0001" if p < 1e-4 else f"{p:.4g}")


def render(rq1: dict, sim: dict) -> str:
    cfg = sim["config"]
    lines = [
        "# C4 Bloom-progression evaluation",
        "",
        "Generated by `python3 scripts/run_c4_progression.py`. Pilot parameters, simulated learners; "
        "see the caveats before quoting any number.",
        "",
        "## RQ4a. Does level-targeted repair keep explanations faithful and hit the target Bloom level?",
        f"- Stress corpus: {rq1['cases']} cases x {len(rq1['learner_starts'])} learner starts "
        f"({', '.join(rq1['learner_starts'])}) = {rq1['runs']} runs. Policy actions taken: {rq1['policy_actions']}.",
        "",
        "| Text measured | Runs | Question at target level % | 95% CI | Runs with a violation | Hallucination % | Cognitive mismatch % |",
        "|---|---|---|---|---|---|---|",
    ]
    names = {"unverified": "Unverified explanation", "static_c4": "Static C4 (current)", "progressive_c4": "Progressive C4"}
    for key, row in rq1["conditions"].items():
        lines.append(f"| {names[key]} | {row['runs']} | {row['question_at_target_level_pct']} | "
                     f"{row['question_at_target_level_ci95']} | {row['runs_with_violation']} | "
                     f"{row['hallucination_rate']} | {row['cognitive_mismatch_rate']} |")
    lines += [f"- Runs with unresolved claims after repair: {rq1['runs_with_unresolved_claims']}.", "",
              f"**Caveat.** {rq1['caveat']}", "",
              "## RQ4b. Does the progression policy raise demonstrated Bloom level across sessions?",
              f"- {cfg['learners']} simulated learners (equal numbers of novice, intermediate, advanced), "
              f"{cfg['sessions']} sessions, seed {cfg['seed']}, target concept `{cfg['target']}`.",
              "- Conditions: **A** unverified; **B** current C4; **C** progressive C4; ablations "
              "**C_no_fading** (generic support) and **C_no_stretch** (never above the demonstrated level).",
              "- Outcome: capability (Bloom levels as a real number) gained from the first to the last session. "
              "Paired differences have a seeded bootstrap 95% interval, a Wilcoxon signed-rank p-value "
              "(normal approximation) and Cohen's dz.", "", "### Assumptions"]
    lines += [f"- {item}" for item in sim["assumptions"]]
    for model, data in sim["models"].items():
        lines += ["", f"### {MODEL_TEXT[model]}", "",
                  "| Condition | Mean final level | Mean capability gain | Reached level 3 % | Mean sessions to level 3* | Too hard % | Too easy % |",
                  "|---|---|---|---|---|---|---|"]
        for name in CONDITIONS + ABLATIONS:
            row = data["conditions"][name]
            lines.append(f"| {name} | {row['mean_final_level']} | {row['mean_capability_gain']} | "
                         f"{row['share_reaching_level_3_pct']} | {row['mean_sessions_to_level_3']} | "
                         f"{row['sessions_too_hard_pct']} | {row['sessions_too_easy_pct']} |")
        lines += ["", "Mean true Bloom level by session:", "",
                  "| Condition | " + " | ".join(f"S{i}" for i in range(1, cfg["sessions"] + 1)) + " |",
                  "|---|" + "---|" * cfg["sessions"]]
        for name in CONDITIONS:
            lines.append(f"| {name} | " + " | ".join(str(v) for v in data["conditions"][name]["trajectory_mean_true_level"]) + " |")
        lines += ["", "Paired comparisons on capability gain (positive favours the first condition):", "",
                  "| Comparison | Mean difference | 95% bootstrap CI | Wilcoxon p | Cohen's dz | Better / worse / equal |",
                  "|---|---|---|---|---|---|"]
        for key, row in data["paired"].items():
            label = key.replace("_", " ")
            lines.append(f"| {label} | {row['mean_difference']} | {row['ci95_bootstrap']} | {fmt_p(row['wilcoxon'])} | "
                         f"{row['cohens_dz']} | {row['learners_better']} / {row['learners_worse']} / {row['learners_equal']} |")
        tracking = data["conditions"]["C_progressive"]["tracking_mae_final"]
        lines += ["", f"Tracking error of the observed Bloom level in C: mean absolute error {tracking} levels "
                      "at the last session.",
                  "", "*Censored at sessions + 1 when level 3 is not reached."]
    lines += ["", "### Sensitivity to study length (C minus B, capability gain)", "",
              "| Sessions | ZPD | Flat | Matched |", "|---|---|---|---|"]
    for sessions, row in sim["sensitivity_sessions"].items():
        cells = [f"{row[m]['mean_difference']} {tuple(row[m]['ci95_bootstrap'])}" for m in ("zpd", "flat", "matched")]
        lines.append(f"| {sessions} | " + " | ".join(cells) + " |")
    lines += ["", f"**Caveat.** {sim['caveat']}", "", "### Reading the results honestly",
              "- The stretch is what helps. The ablation without it loses most of the gain, while removing the fading gives no gain or loss beyond noise in this learner model (it has no dependence effect for fading to protect).",
              "- Progression does not speed up reaching level 3; it raises the level reached later, and the benefit needs enough sessions (about zero at 4, clear at 8, larger at 12).",
              "- When stretching does not help learners (matched control) the mechanism ties at best and is slower to level 3; under 12 sessions it is worse.",
              "- The policy starts every unseen concept at Remember, so learners who start high lose early sessions; a placement check would address this.",
              "- The observed Bloom level lags or leads the true level (tracking error above), which limits how well the policy can aim."]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--learners", type=int, default=300)
    parser.add_argument("--sessions", type=int, default=8)
    parser.add_argument("--seed", type=int, default=2026)
    args = parser.parse_args()

    kg = load_json(DATA / "knowledge_graph.json")
    RESULTS.mkdir(exist_ok=True)
    rq1 = evaluate_progressive_stress(kg)
    sim = run_experiment(kg, args.learners, args.sessions, args.seed)
    (RESULTS / "progression.json").write_text(json.dumps({"rq1": rq1, "rq2": sim}, indent=2) + "\n", encoding="utf-8")
    report = render(rq1, sim)
    (RESULTS / "PROGRESSION.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
